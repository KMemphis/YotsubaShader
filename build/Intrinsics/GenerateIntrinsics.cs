// Tarea de MSBuild que genera Math.g.cs, Intrinsic.g.cs y Placeholders.g.cs a partir del JSON de una sintaxis.
// MSBuild la compila sola (RoslynCodeTaskFactory) desde Intrinsics.targets: no hace falta Python ni otro proyecto.
// Este archivo NO forma parte de ninguna librería; solo lo usa el build.
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.Build.Framework;

public class GenerateIntrinsics : Microsoft.Build.Utilities.Task
{
    [Required] public string JsonFile { get; set; }
    [Required] public string OutputDirectory { get; set; }

    /// <summary>Ruta a Intrinsic.cs. Si existe, sus valores sustituyen a "knownIntrinsics" del JSON.</summary>
    public string EnumFile { get; set; }

    static readonly HashSet<string> Keywords = new HashSet<string>((
        "abstract as base bool break byte case catch char checked class const continue decimal default delegate do " +
        "double else enum event explicit extern false finally fixed float for foreach goto if implicit in int " +
        "interface internal is lock long namespace new null object operator out override params private protected " +
        "public readonly ref return sbyte sealed short sizeof stackalloc static string struct switch this throw true " +
        "try typeof uint ulong unchecked unsafe ushort using virtual void volatile while").Split(' '));

    public override bool Execute()
    {
        try
        {
            var data = (Dictionary<string, object>)new Json(File.ReadAllText(JsonFile)).Parse();
            var known = new HashSet<string>(
                !string.IsNullOrEmpty(EnumFile) && File.Exists(EnumFile)
                    ? ReadEnum(EnumFile)
                    : List(data, "knownIntrinsics").Select(v => (string)v));

            Directory.CreateDirectory(OutputDirectory);
            string jsonName = Path.GetFileName(JsonFile);
            Write("Math.g.cs", ClassFile(data, "Math", jsonName, known));
            Write("Intrinsic.g.cs", ClassFile(data, "Intrinsic", jsonName, known));
            Write("Placeholders.g.cs", PlaceholdersFile(data, jsonName));
            return true;
        }
        catch (Exception e)
        {
            Log.LogError("GenerateIntrinsics: no se pudo generar desde '{0}': {1}", JsonFile, e.Message);
            return false;
        }
    }

    void Write(string name, string content)
    {
        string path = Path.Combine(OutputDirectory, name);
        if (!File.Exists(path) || File.ReadAllText(path) != content)
            File.WriteAllText(path, content, new UTF8Encoding(false));
        else
            File.SetLastWriteTimeUtc(path, DateTime.UtcNow); // mantiene al día la comprobación incremental
    }

    static IEnumerable<string> ReadEnum(string path)
    {
        string text = File.ReadAllText(path);
        int start = text.IndexOf("enum Intrinsic", StringComparison.Ordinal);
        if (start < 0) return Enumerable.Empty<string>();
        string body = Regex.Replace(text.Substring(start), @"//.*", "");
        return Regex.Matches(body, @"\b([A-Z]\w*)\s*,").Cast<Match>().Select(m => m.Groups[1].Value);
    }

    // ---------------------------------------------------------------- helpers de acceso al JSON
    static string Str(Dictionary<string, object> d, string key)
    {
        object v;
        return d.TryGetValue(key, out v) ? v as string : null;
    }

    static List<object> List(Dictionary<string, object> d, string key)
    {
        object v;
        return d.TryGetValue(key, out v) && v is List<object> ? (List<object>)v : new List<object>();
    }

    static string Esc(string name) { return Keywords.Contains(name) ? "@" + name : name; }

    static string TypeName(string key) { int i = key.IndexOf('<'); return i < 0 ? key : key.Substring(0, i); }

    static string[] TypeParams(string key)
    {
        int i = key.IndexOf('<');
        if (i < 0) return new string[0];
        return key.Substring(i + 1, key.Length - i - 2).Split(',').Select(p => p.Trim()).ToArray();
    }

    const string Header =
        "// <auto-generated>\n" +
        "//   Generado al compilar por GenerateIntrinsics a partir de {0}.\n" +
        "//   No lo edites a mano: cambia el JSON y vuelve a compilar.\n" +
        "// </auto-generated>\n";

    // ---------------------------------------------------------------- usings y alias de tipos
    static List<string> Usings(Dictionary<string, object> data)
    {
        var types = (Dictionary<string, object>)data["types"];
        string placeholderNs = Str(data, "placeholderNamespace");
        var aliases = new List<string>();
        var namespaces = new SortedSet<string>(StringComparer.Ordinal);
        bool needsPlaceholderNs = false;

        foreach (var pair in types)
        {
            string name = TypeName(pair.Key);
            string target = pair.Value as string;
            if (TypeParams(pair.Key).Length > 0)
            {
                // C# no permite alias de genéricos abiertos: se importa el namespace del tipo.
                if (target != null)
                {
                    string open = target.Substring(0, target.IndexOf('<'));
                    namespaces.Add(open.Substring(0, open.LastIndexOf('.')));
                }
                else needsPlaceholderNs = true;
                continue;
            }
            string full = target ?? placeholderNs + "." + name;
            aliases.Add("using " + Esc(name) + " = " + string.Join(".", full.Split('.').Select(Esc)) + ";");
        }

        var lines = new List<string> { "using System;", "using YotsubaShader.Concepts.Methods;" };
        lines.AddRange(namespaces.Select(ns => "using " + ns + ";"));
        if (needsPlaceholderNs) lines.Add("using " + placeholderNs + ";");
        lines.Add("using Intrinsics = YotsubaShader.Concepts.Methods.Intrinsic;");
        if (aliases.Count > 0)
        {
            lines.Add("");
            lines.Add("// Tipos usados en las firmas. El destino sale del campo \"types\" del JSON.");
            lines.AddRange(aliases);
        }
        return lines;
    }

    // ---------------------------------------------------------------- un método
    static void Method(List<string> lines, Dictionary<string, object> overload, HashSet<string> known)
    {
        const string I = "        ";
        string intrinsic = Str(overload, "intrinsic");
        if (intrinsic != null && known.Contains(intrinsic))
            lines.Add(I + "[IntrinsicMethod(Intrinsics." + intrinsic + ")]");
        else if (intrinsic != null)
            lines.Add(I + "// TODO: falta Intrinsic." + intrinsic + " en el enum; al añadirlo, el atributo aparece solo.");
        else
            lines.Add(I + "// TODO: sin valor de Intrinsic asignado.");

        var parameters = new List<string>();
        foreach (Dictionary<string, object> p in List(overload, "params"))
        {
            string modifier = Str(p, "modifier");
            parameters.Add((modifier != null ? modifier + " " : "") + Str(p, "type") + " " + Esc(Str(p, "name")));
        }
        var typeParams = List(overload, "typeParams").Select(t => (string)t).ToList();
        string generic = typeParams.Count > 0 ? "<" + string.Join(", ", typeParams) + ">" : "";

        lines.Add(I + "public static " + Str(overload, "returns") + " " + Esc(Str(overload, "name")) + generic +
                  "(" + string.Join(", ", parameters) + ")");
        foreach (string tp in typeParams) lines.Add(I + "    where " + tp + " : unmanaged");
        lines.Add(I + "{");
        lines.Add(I + "    throw new InvalidOperationException();");
        lines.Add(I + "}");
    }

    // ---------------------------------------------------------------- Math.g.cs / Intrinsic.g.cs
    static string ClassFile(Dictionary<string, object> data, string klass, string jsonName, HashSet<string> known)
    {
        var lines = new List<string> { string.Format(Header, jsonName).TrimEnd() };
        lines.AddRange(Usings(data));
        lines.Add("");
        lines.Add("namespace " + Str(data, "namespace"));
        lines.Add("{");
        lines.Add("    public static class " + klass);
        lines.Add("    {");

        string section = null;
        foreach (Dictionary<string, object> fn in List(data, "functions"))
        {
            if (Str(fn, "class") != klass) continue;
            if (Str(fn, "section") != section)
            {
                section = Str(fn, "section");
                string bar = "        // " + new string('=', 84);
                lines.Add(bar);
                lines.Add("        // " + section);
                lines.Add(bar);
                lines.Add("");
            }

            var overloads = List(fn, "overloads");
            if (overloads.Count == 0)
            {
                string reason = Str(fn, "note") ?? "sin sobrecargas generables (mira \"skipped\" en el JSON)";
                lines.Add("        // " + Str(fn, "concept") + ": " + reason + ".");
                lines.Add("");
                continue;
            }

            var names = new List<string>();
            foreach (Dictionary<string, object> ov in overloads)
                if (!names.Contains(Str(ov, "name"))) names.Add(Str(ov, "name"));

            lines.Add("        #region " + string.Join(" / ", names) + " — " + Str(fn, "concept"));
            foreach (Dictionary<string, object> ov in overloads)
            {
                lines.Add("");
                Method(lines, ov, known);
            }
            lines.Add("");
            lines.Add("        #endregion");
            lines.Add("");
        }

        lines.Add("    }");
        lines.Add("}");
        lines.Add("");
        return string.Join("\n", lines);
    }

    // ---------------------------------------------------------------- Placeholders.g.cs
    static string PlaceholdersFile(Dictionary<string, object> data, string jsonName)
    {
        var entries = new List<string>();
        foreach (var pair in (Dictionary<string, object>)data["types"])
        {
            if (pair.Value is string) continue; // ya tiene tipo real
            string name = TypeName(pair.Key);
            string[] typeParams = TypeParams(pair.Key);
            if (typeParams.Length > 0)
                entries.Add("    public struct " + Esc(name) + "<" + string.Join(", ", typeParams) + ">" +
                            string.Concat(typeParams.Select(p => " where " + p + " : unmanaged")) + " { }");
            else
                entries.Add("    public struct " + Esc(name) + " { }");
        }

        var lines = new List<string> { string.Format(Header, jsonName).TrimEnd(), "" };
        if (entries.Count == 0)
        {
            lines.Add("// Todos los tipos del JSON tienen ya un tipo real: no hace falta ningún relleno.");
        }
        else
        {
            lines.Add("// Tipos de relleno: existen solo para que las firmas compilen.");
            lines.Add("// Pon el nombre completo del tipo real en \"types\" del JSON y el relleno desaparece.");
            lines.Add("namespace " + Str(data, "placeholderNamespace"));
            lines.Add("{");
            lines.AddRange(entries);
            lines.Add("}");
        }
        lines.Add("");
        return string.Join("\n", lines);
    }

    // ---------------------------------------------------------------- lector de JSON mínimo, sin dependencias
    sealed class Json
    {
        readonly string _s;
        int _i;

        public Json(string text) { _s = text; }

        public object Parse()
        {
            object value = Value();
            Space();
            if (_i != _s.Length) throw Error("sobra texto al final");
            return value;
        }

        Exception Error(string message) { return new FormatException("JSON inválido en la posición " + _i + ": " + message); }

        void Space() { while (_i < _s.Length && char.IsWhiteSpace(_s[_i])) _i++; }

        object Value()
        {
            Space();
            if (_i >= _s.Length) throw Error("fin inesperado");
            char c = _s[_i];
            if (c == '{') return Object();
            if (c == '[') return Array();
            if (c == '"') return String();
            if (Literal("true")) return true;
            if (Literal("false")) return false;
            if (Literal("null")) return null;
            return Number();
        }

        bool Literal(string word)
        {
            if (string.CompareOrdinal(_s, _i, word, 0, word.Length) != 0) return false;
            _i += word.Length;
            return true;
        }

        Dictionary<string, object> Object()
        {
            var result = new Dictionary<string, object>(StringComparer.Ordinal);
            _i++;
            Space();
            if (_s[_i] == '}') { _i++; return result; }
            while (true)
            {
                Space();
                string key = String();
                Space();
                if (_s[_i++] != ':') throw Error("se esperaba ':'");
                result[key] = Value();
                Space();
                char c = _s[_i++];
                if (c == '}') return result;
                if (c != ',') throw Error("se esperaba ',' o '}'");
            }
        }

        List<object> Array()
        {
            var result = new List<object>();
            _i++;
            Space();
            if (_s[_i] == ']') { _i++; return result; }
            while (true)
            {
                result.Add(Value());
                Space();
                char c = _s[_i++];
                if (c == ']') return result;
                if (c != ',') throw Error("se esperaba ',' o ']'");
            }
        }

        string String()
        {
            if (_s[_i] != '"') throw Error("se esperaba una cadena");
            _i++;
            var sb = new StringBuilder();
            while (true)
            {
                char c = _s[_i++];
                if (c == '"') return sb.ToString();
                if (c != '\\') { sb.Append(c); continue; }
                char e = _s[_i++];
                switch (e)
                {
                    case 'n': sb.Append('\n'); break;
                    case 't': sb.Append('\t'); break;
                    case 'r': sb.Append('\r'); break;
                    case 'b': sb.Append('\b'); break;
                    case 'f': sb.Append('\f'); break;
                    case 'u':
                        sb.Append((char)int.Parse(_s.Substring(_i, 4), NumberStyles.HexNumber, CultureInfo.InvariantCulture));
                        _i += 4;
                        break;
                    default: sb.Append(e); break;
                }
            }
        }

        object Number()
        {
            int start = _i;
            while (_i < _s.Length && "+-0123456789.eE".IndexOf(_s[_i]) >= 0) _i++;
            if (start == _i) throw Error("valor no reconocido");
            return double.Parse(_s.Substring(start, _i - start), CultureInfo.InvariantCulture);
        }
    }
}
