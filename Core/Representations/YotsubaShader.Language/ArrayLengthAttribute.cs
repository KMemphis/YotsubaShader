using System;

namespace YotsubaShader.Language
{
    /// <summary>
    /// La longitud de un array que C# no lleva en el tipo: campos de structs de interfaz, de uniform buffers o de
    /// storage buffers. <c>[ArrayLength(16)] public float4[] Lights;</c> es <c>float4 Lights[16]</c> en la GPU.
    /// Un array sin este atributo, como último miembro de un storage buffer, no tiene tamaño fijo
    /// (<c>RWStructuredBuffer</c>, <c>buffer { T data[]; }</c>).
    /// </summary>
    [AttributeUsage(AttributeTargets.Field | AttributeTargets.Property | AttributeTargets.Parameter | AttributeTargets.ReturnValue)]
    public sealed class ArrayLengthAttribute : YotsubaShaderAttribute
    {
        public ArrayLengthAttribute(int length)
        {
            if (length < 1) throw new ArgumentOutOfRangeException(nameof(length), length, "An array needs at least one element.");
            Length = length;
        }

        public int Length { get; }
    }
}
