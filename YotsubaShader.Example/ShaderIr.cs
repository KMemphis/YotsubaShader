using YotsubaShader.IR.Intermediate;
using YotsubaShader.IR.Intermediate.FunctionBody;
using YotsubaShader.IR.Intermediate.FunctionBody.Expressions.FunctionCalls;
using YotsubaShader.IR.Intermediate.FunctionBody.Statements;
using YotsubaShader.Roslyn;

namespace YotsubaShader.Example;

/// <summary>Puerta 2 del libro: del texto de C# al IR, para probar el front-end sin pasar por SPIR-V.</summary>
internal static class ShaderIr
{
    public static Shader Process(string code)
    {
        var compilation = TestCompilation.Create(code);
        var (_, shader) = Assert.Single(new ShaderProcessor().Process(compilation, CancellationToken.None));
        return shader;
    }

    public static Function Single(this Shader shader, string name) =>
        Assert.Single(shader.Functions, f => f.HumanName == name);

    /// <summary>La expresión con la que se inicializa la variable local <paramref name="local"/>.</summary>
    public static Expression InitializerOf(this Function function, string local) =>
        Flatten(function.Body).OfType<VariableDeclaration>()
            .Single(d => d.Storage.HumanName == local).Initializer!;

    /// <summary>Las sentencias de la función con los bloques anidados aplanados (`T x = ...;` llega dentro de un Block).</summary>
    public static IEnumerable<Statement> Flatten(IEnumerable<Statement> statements)
    {
        foreach (Statement statement in statements)
        {
            if (statement is Block block)
            {
                foreach (Statement inner in Flatten(block.Statements)) yield return inner;
            }
            else
            {
                yield return statement;
            }
        }
    }

    public static FunctionCallExpression CallInitializerOf(this Function function, string local) =>
        Assert.IsType<FunctionCallExpression>(function.InitializerOf(local));
}
